use std::future::Future;
use std::marker::PhantomData;
use std::pin::Pin;

use tonic::codec::ProstCodec;
use tonic::server::{Grpc, UnaryService};
use tonic::Status;

use crate::context::{CallContext, CallParts};

/// Boxed response future returned by every registered handler.
pub type HandlerFuture =
    Pin<Box<dyn Future<Output = http::Response<tonic::body::BoxBody>> + Send + 'static>>;

/// Type-erased unary handler: raw HTTP/2 gRPC request in, encoded gRPC response out.
pub type Handler = fn(http::Request<axum::body::Body>) -> HandlerFuture;

/// One `#[grpc]` function, submitted to [`inventory`] by the macro.
pub struct GrpcMethod {
    /// Fully qualified proto service, version included (`biyard.greeter.v1.Greeter`).
    pub service: &'static str,
    /// Proto method name (`SayHello`).
    pub method: &'static str,
    /// Package version segment (`v1`).
    pub version: &'static str,
    /// gRPC route (`/biyard.greeter.v1.Greeter/SayHello`).
    pub path: &'static str,
    /// Fully qualified proto name of the request message, from `prost::Name`.
    pub request_type: fn() -> String,
    /// Fully qualified proto name of the response message, from `prost::Name`.
    pub response_type: fn() -> String,
    pub handler: Handler,
    /// Rust path of the annotated function, for diagnostics.
    pub source: &'static str,
}

struct Once<F, Req, Resp, Fut>(Option<F>, PhantomData<fn() -> (Req, Resp, Fut)>);

impl<F, Req, Resp, Fut> UnaryService<Req> for Once<F, Req, Resp, Fut>
where
    F: FnOnce(CallParts, Req) -> Fut + Send + 'static,
    Req: Send + 'static,
    Fut: Future<Output = Result<tonic::Response<Resp>, Status>> + Send + 'static,
{
    type Response = Resp;
    type Future = Pin<Box<dyn Future<Output = Result<tonic::Response<Resp>, Status>> + Send>>;

    fn call(&mut self, request: tonic::Request<Req>) -> Self::Future {
        let handler = self.0.take();
        Box::pin(async move {
            let handler = handler.ok_or_else(|| Status::internal("unary handler polled twice"))?;
            let (metadata, extensions, message) = request.into_parts();
            let context = CallContext::from_metadata(&metadata)?;
            let parts = CallParts {
                metadata,
                extensions,
                context,
            };
            handler(parts, message).await
        })
    }
}

/// Decodes `Req`, runs `handler`, and encodes `Resp` with tonic's prost codec.
///
/// Called only from code generated by `#[grpc]`.
pub fn unary<Req, Resp, F, Fut>(request: http::Request<axum::body::Body>, handler: F) -> HandlerFuture
where
    Req: prost::Message + Default + Send + 'static,
    Resp: prost::Message + Send + 'static,
    F: FnOnce(CallParts, Req) -> Fut + Send + 'static,
    Fut: Future<Output = Result<tonic::Response<Resp>, Status>> + Send + 'static,
{
    Box::pin(async move {
        let mut grpc = Grpc::new(ProstCodec::<Resp, Req>::default());
        grpc.unary(Once(Some(handler), PhantomData), request).await
    })
}
